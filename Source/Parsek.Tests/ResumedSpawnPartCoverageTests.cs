using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using Parsek.Analyzer;
using Parsek.Analyzer.Rules;
using Xunit;

namespace Parsek.Tests
{
    /// <summary>
    /// A Parsek spawn regenerates every part persistentId, so a spawned vessel flown again
    /// must not record into the committed recording that spawned it: that recording's ghost
    /// snapshot still names the first session's parts, and ghost playback (and the INV4
    /// analyzer rule) resolve part events against it. MINE-13 `2026-10-17_1525` measured the
    /// defect (INV4-PARTEVENT-PID x8). The restore now continues in a new switch-continuation
    /// segment when the snapshot does not hold the live part pids.
    /// </summary>
    [Collection("Sequential")]
    public class ResumedSpawnPartCoverageTests : IDisposable
    {
        private readonly List<string> logLines = new List<string>();

        public ResumedSpawnPartCoverageTests()
        {
            ParsekLog.ResetTestOverrides();
            ParsekLog.SuppressLogging = false;
            ParsekLog.VerboseOverrideForTesting = true;
            ParsekLog.TestSinkForTesting = line => logLines.Add(line);
        }

        public void Dispose()
        {
            ParsekLog.ResetTestOverrides();
            ParsekLog.SuppressLogging = true;
        }

        private static ConfigNode Snapshot(params uint[] partPids)
        {
            var vessel = new ConfigNode("VESSEL");
            for (int i = 0; i < partPids.Length; i++)
            {
                ConfigNode part = vessel.AddNode("PART");
                part.AddValue("name", "part" + i.ToString(CultureInfo.InvariantCulture));
                part.AddValue("persistentId", partPids[i].ToString(CultureInfo.InvariantCulture));
            }
            return vessel;
        }

        private static readonly uint[] Session1Pids = { 100000u, 101111u, 102222u };
        private static readonly uint[] SpawnPids = { 900001u, 900002u, 900003u };

        // ---- the predicate's truth table -------------------------------------------------

        // catches: the original vessel resumed with its own parts being moved to a new
        // segment (the identity-covered case must stay exactly as before).
        [Fact]
        public void SameParts_AreCovered()
        {
            var c = ResumedSpawnPartCoverage.Evaluate(Snapshot(Session1Pids), "ghost", Session1Pids);
            Assert.True(c.Covered);
            Assert.Equal(ResumedSpawnPartCoverage.ReasonAllCovered, c.Reason);
            Assert.Equal(3, c.LivePartCount);
            Assert.Equal(3, c.SnapshotPartCount);
            Assert.Equal(0, c.UncoveredPartCount);
        }

        // catches: a vessel that staged since its snapshot (fewer live parts) read as a
        // different vessel.
        [Fact]
        public void LiveSubsetOfSnapshot_IsCovered()
        {
            var c = ResumedSpawnPartCoverage.Evaluate(
                Snapshot(Session1Pids), "ghost", new[] { 100000u, 101111u });
            Assert.True(c.Covered);
            Assert.Equal(ResumedSpawnPartCoverage.ReasonAllCovered, c.Reason);
        }

        // catches: the defect shape. Every part pid regenerated by the spawn.
        [Fact]
        public void RegeneratedParts_AreNotCovered()
        {
            var c = ResumedSpawnPartCoverage.Evaluate(Snapshot(Session1Pids), "ghost", SpawnPids);
            Assert.False(c.Covered);
            Assert.Equal(ResumedSpawnPartCoverage.ReasonUncoveredParts, c.Reason);
            Assert.Equal(3, c.LivePartCount);
            Assert.Equal(3, c.UncoveredPartCount);
        }

        // catches: a single live part the snapshot lacks being let through (its events would
        // be the unresolved ones).
        [Fact]
        public void OneExtraLivePart_IsNotCovered()
        {
            var c = ResumedSpawnPartCoverage.Evaluate(
                Snapshot(Session1Pids), "ghost", new[] { 100000u, 101111u, 102222u, 777777u });
            Assert.False(c.Covered);
            Assert.Equal(1, c.UncoveredPartCount);
        }

        // catches: nothing to compare turning into a forced new segment.
        [Fact]
        public void NoSnapshot_IsCovered_ResumeAsToday()
        {
            var c = ResumedSpawnPartCoverage.Evaluate((ConfigNode)null, "ghost", SpawnPids);
            Assert.True(c.Covered);
            Assert.Equal(ResumedSpawnPartCoverage.ReasonNoSnapshot, c.Reason);
            Assert.Equal("none", c.SnapshotSource);
        }

        [Fact]
        public void SnapshotWithoutParts_IsCovered()
        {
            var c = ResumedSpawnPartCoverage.Evaluate(new ConfigNode("VESSEL"), "vessel", SpawnPids);
            Assert.True(c.Covered);
            Assert.Equal(ResumedSpawnPartCoverage.ReasonSnapshotWithoutParts, c.Reason);
        }

        [Fact]
        public void NoLiveParts_IsCovered()
        {
            Assert.Equal(ResumedSpawnPartCoverage.ReasonNoLiveParts,
                ResumedSpawnPartCoverage.Evaluate(Snapshot(Session1Pids), "ghost", null).Reason);
            var zeros = ResumedSpawnPartCoverage.Evaluate(Snapshot(Session1Pids), "ghost", new[] { 0u, 0u });
            Assert.True(zeros.Covered);
            Assert.Equal(ResumedSpawnPartCoverage.ReasonNoLiveParts, zeros.Reason);
        }

        // catches: a duplicated live pid inflating the counts the decision line logs.
        [Fact]
        public void DuplicateAndZeroLivePids_CountOnce()
        {
            var c = ResumedSpawnPartCoverage.Evaluate(
                Snapshot(Session1Pids), "ghost", new[] { 900001u, 900001u, 0u });
            Assert.False(c.Covered);
            Assert.Equal(1, c.LivePartCount);
            Assert.Equal(1, c.UncoveredPartCount);
        }

        // catches: the recording overload reading the vessel (end) snapshot first. Playback
        // and INV4 read the ghost snapshot first; a commit refreshes only the vessel snapshot
        // from the live vessel, so after a resume the two can disagree.
        [Fact]
        public void RecordingOverload_ReadsTheGhostSnapshotFirst()
        {
            var rec = new Recording
            {
                RecordingId = "rec-miner",
                GhostVisualSnapshot = Snapshot(Session1Pids),
                VesselSnapshot = Snapshot(SpawnPids),
            };
            var c = ResumedSpawnPartCoverage.Evaluate(rec, SpawnPids);
            Assert.False(c.Covered);
            Assert.Equal("ghost", c.SnapshotSource);
        }

        [Fact]
        public void RecordingOverload_FallsBackToTheVesselSnapshot()
        {
            var rec = new Recording { RecordingId = "rec-miner", VesselSnapshot = Snapshot(Session1Pids) };
            var c = ResumedSpawnPartCoverage.Evaluate(rec, SpawnPids);
            Assert.False(c.Covered);
            Assert.Equal("vessel", c.SnapshotSource);

            var none = ResumedSpawnPartCoverage.Evaluate((Recording)null, SpawnPids);
            Assert.True(none.Covered);
            Assert.Equal(ResumedSpawnPartCoverage.ReasonNoSnapshot, none.Reason);
        }

        // ---- the stock click adopting the resumed-spawn segment ---------------------------

        private static SwitchSegmentSession ResumedSession() => new SwitchSegmentSession
        {
            SessionId = Guid.NewGuid(),
            TreeId = "tree-miner",
            ParentRecordingId = "rec-miner",
            ActiveSegmentRecordingId = "seg-1",
            FocusedVesselPersistentId = 4242u,
            EntryReason = SwitchSegmentEntryReason.ResumedSpawnedVessel,
            IntentId = Guid.Empty,
        };

        // catches: a TS Fly consumed after the 1 Hz restore already continued in a segment
        // stacking a second segment under it, or adopting a session it does not own.
        [Fact]
        public void AdoptableSession_TruthTable()
        {
            Assert.True(ParsekFlight.IsAdoptableResumedSpawnSession(
                ResumedSession(), "tree-miner", "seg-1", 4242u));

            Assert.False(ParsekFlight.IsAdoptableResumedSpawnSession(null, "tree-miner", "seg-1", 4242u));
            Assert.False(ParsekFlight.IsAdoptableResumedSpawnSession(
                ResumedSession(), "tree-other", "seg-1", 4242u));
            Assert.False(ParsekFlight.IsAdoptableResumedSpawnSession(
                ResumedSession(), "tree-miner", "rec-miner", 4242u));
            Assert.False(ParsekFlight.IsAdoptableResumedSpawnSession(
                ResumedSession(), "tree-miner", "seg-1", 4343u));
            Assert.False(ParsekFlight.IsAdoptableResumedSpawnSession(
                ResumedSession(), "tree-miner", "seg-1", 0u));

            SwitchSegmentSession stockOwned = ResumedSession();
            stockOwned.EntryReason = SwitchSegmentEntryReason.TrackingStationFly;
            Assert.False(ParsekFlight.IsAdoptableResumedSpawnSession(
                stockOwned, "tree-miner", "seg-1", 4242u));
        }

        // catches: the new entry reason (and its empty intent id) not surviving a save / load
        // (TryLoadFrom rejects an unknown reason, which would drop the session on reload).
        [Fact]
        public void ResumedSpawnSession_RoundTrips()
        {
            SwitchSegmentSession session = ResumedSession();
            var parent = new ConfigNode("PARSEK");
            session.SaveInto(parent);

            Assert.True(SwitchSegmentSession.TryLoadFrom(
                parent.GetNode(SwitchSegmentSession.NodeName), out SwitchSegmentSession loaded));
            Assert.Equal(SwitchSegmentEntryReason.ResumedSpawnedVessel, loaded.EntryReason);
            Assert.Equal(Guid.Empty, loaded.IntentId);
            Assert.Equal(session.SessionId, loaded.SessionId);
            Assert.Equal("seg-1", loaded.ActiveSegmentRecordingId);
        }

        // ---- end to end over pure seams: the segment's part events resolve ----------------

        private static TrajectoryPoint Boundary(double ut) => new TrajectoryPoint
        {
            ut = ut,
            altitude = 66.0,
            bodyName = "Kerbin",
        };

        private static RecordingTree RestoredMinerTree(out Recording target)
        {
            var tree = new RecordingTree
            {
                Id = "tree-miner",
                TreeName = "Mining Rover RC",
                BranchPoints = new List<BranchPoint>(),
            };
            // The committed recording after the restore re-pidded it to the live spawn pid
            // (TryTakeCommittedTreeForSpawnedVesselRestore); its snapshots still carry the
            // first session's part pids, and its part events name them.
            target = new Recording
            {
                RecordingId = "rec-miner",
                TreeId = tree.Id,
                VesselPersistentId = 4242u,
                VesselName = "Mining Rover RC",
                ExplicitStartUT = 0.0,
                GhostVisualSnapshot = Snapshot(Session1Pids),
                VesselSnapshot = Snapshot(Session1Pids),
            };
            target.Points.Add(Boundary(0.0));
            target.Points.Add(Boundary(1830.0));
            target.PartEvents.Add(new PartEvent
            {
                ut = 60.0, partPersistentId = 101111u, eventType = PartEventType.ConverterActivated,
            });
            tree.AddOrReplaceRecording(target);
            tree.RootRecordingId = target.RecordingId;
            tree.ActiveRecordingId = target.RecordingId;
            return tree;
        }

        private static List<Finding> RunInv4(RecordingTree tree)
        {
            var model = new AnalyzerModel
            {
                SaveName = "resumed-spawn",
                Recordings = tree.Recordings.Values.ToList(),
                Trees = new List<RecordingTree> { tree },
            };
            return new Inv4PartEventPid().Evaluate(model).ToList();
        }

        private static List<PartEvent> Session2Events() => new List<PartEvent>
        {
            new PartEvent { ut = 1840.0, partPersistentId = 900001u, eventType = PartEventType.RoboticMotionStarted },
            new PartEvent { ut = 1841.0, partPersistentId = 900002u, eventType = PartEventType.ConverterActivated },
        };

        // The defect, reproduced over the model: session 2's events recorded INTO the
        // committed recording do not resolve against its snapshot.
        [Fact]
        public void RecordingIntoTheTarget_LeavesUnresolvedPartEvents()
        {
            RecordingTree tree = RestoredMinerTree(out Recording target);
            target.PartEvents.AddRange(Session2Events());

            List<Finding> findings = RunInv4(tree);

            Assert.Equal(2, findings.Count(f => f.Level == VerdictLevel.Fail));
        }

        // catches: the fix's shape. The restore decides "not covered", attaches a
        // ResumedSpawnedVessel segment under the target, the recorder's start backstop gives
        // the segment the live snapshot, and session 2's events land on the segment: every
        // part event in the tree resolves.
        [Fact]
        public void ContinuingInANewSegment_ResolvesEveryPartEvent()
        {
            RecordingTree tree = RestoredMinerTree(out Recording target);

            ResumedPartCoverage coverage = ResumedSpawnPartCoverage.Evaluate(target, SpawnPids);
            Assert.False(coverage.Covered);

            var creation = SwitchSegmentBuilder.CreateSwitchContinuationSegment(
                tree, target.RecordingId, focusedVesselPersistentId: 4242u,
                focusedVesselName: "Mining Rover RC", switchUT: 1835.0,
                entryReason: SwitchSegmentEntryReason.ResumedSpawnedVessel,
                intentId: Guid.Empty, sessionId: Guid.NewGuid(),
                newRecordingId: "seg-resumed", newBranchPointId: "bp-resumed",
                initialBoundaryPointFactory: Boundary,
                sourceVesselPersistentId: 0u);
            Assert.True(creation.Created, creation.FailureReason);
            Assert.Equal("seg-resumed", tree.ActiveRecordingId);
            Assert.Equal("bp-resumed", target.ChildBranchPointId);

            bool changed = FlightRecorder.ApplyStartRecordingTreeBackstop(
                tree, null, null, null, null, null, null, null, Snapshot(SpawnPids));
            Assert.True(changed);

            Recording segment = tree.Recordings["seg-resumed"];
            segment.PartEvents.AddRange(Session2Events());

            Assert.Empty(RunInv4(tree));
            // The target keeps only its own session's events.
            Assert.Single(target.PartEvents);
            Assert.Contains(logLines, l => l.Contains("[SwitchSegment]")
                && l.Contains("created ")
                && l.Contains("segmentRecId=seg-resumed")
                && l.Contains("reason=ResumedSpawnedVessel"));
        }
    }
}
